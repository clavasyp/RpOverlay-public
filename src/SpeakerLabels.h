#pragma once

#include <QHash>
#include <QString>

// SpeakerLabels — отображение целочисленных ID кластеров диаризации (0,1,2,…) в человекочитаемые
// метки сцены ("A","B","C",…, далее "A2"… на всякий) в порядке ПЕРВОГО появления, плюс ручное
// переименование (UI). Состояние — на одну «сцену»; reset() начинает новую (метки переназначаются).
//
// Зачем порядок первого появления, а не прямой speaker→буква: ID кластеров от прогона к прогону
// нестабильны (diariation может выдать спикера 2 раньше спикера 0). Стабилизируем по порядку
// появления В ТЕКУЩЕМ результате, чтобы «A» — это первый заговоривший.
class SpeakerLabels {
public:
    // Метка для cluster-ID. При первом обращении назначает следующую свободную букву.
    QString labelFor(int speaker);

    // Ручное переименование (имя пустое → вернуться к авто-букве).
    void rename(int speaker, const QString &name);

    // Новая сцена: сбросить все назначения и ручные имена.
    void reset();

private:
    static QString autoName(int idx);  // 0→"A",1→"B",…,25→"Z",26→"A2",…

    QHash<int, int> order_;       // speaker-ID → порядковый индекс появления
    QHash<int, QString> custom_;  // speaker-ID → ручное имя (перекрывает авто)
    int next_ = 0;                // следующий порядковый индекс
};
